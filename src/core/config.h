/* ============================================================================
 * SnakeGame 核心逻辑层 —— 游戏配置常量
 * ----------------------------------------------------------------------------
 * 集中定义棋盘尺寸与玩法数值，供 core（逻辑）与 ui（渲染/布局）共同引用。
 * 本文件为纯数据常量，不含任何 raylib 依赖。
 * ==========================================================================*/

#ifndef SNAKE_CORE_CONFIG_H
#define SNAKE_CORE_CONFIG_H

/* ------------------------------ 棋盘尺寸 -------------------------------- */
/* 细密网格：格子更多更小，蛇每步位移很小，视觉上看不出“跳格”，更丝滑。
 * 蛇身每节在渲染时占 2x2 格（见 ui/render.c），道具/食物占 1 格。 */
#define GRID_COLS            64   /**< 棋盘列数 */
#define GRID_ROWS            48   /**< 棋盘行数 */

/* ------------------------------ 初始状态 -------------------------------- */
#define INITIAL_SNAKE_LENGTH 6    /**< 初始蛇长（细格数） */
#define SCORE_PER_FOOD       10   /**< 每个普通食物得分 */

/* ------------------------------ 难度成长 -------------------------------- */
#define FOODS_PER_LEVEL      8    /**< 每吃这么多食物升 1 级 */
#define GAME_INPUT_BUFFER    2    /**< 转向输入缓冲队列长度（快速连转不丢输入） */
/* 速度按细格等比折算：每步位移减半，故步进毫秒也减半，保持原有像素速度 */
#define SPEED_BASE_MS        75   /**< 1 级时每格步进毫秒 */
#define SPEED_STEP_MS        4    /**< 每升 1 级减少的毫秒 */
#define SPEED_MIN_MS         35   /**< 速度下限（毫秒，越小越快） */
#define OBSTACLES_PER_LEVELS 3    /**< 每升这么多级增加 1 个障碍 */
#define MAX_OBSTACLES        15   /**< 障碍物数量上限 */

#endif /* SNAKE_CORE_CONFIG_H */
